/** 各种类的品种清单（每份均已按拼音排序），键为种类名 */
export const PET_BREEDS = Object.fromEntries(
  Object.entries(BREEDS_RAW).map(([species, list]) => [species, [...list].sort(byPinyin)]),
)

/**
 * 获取指定种类的品种清单
 * @param {string} species 种类名
 * @returns {string[]} 已排序的品种数组；无匹配种类时返回空数组（此时可由用户自行填写）
 */
export const getBreedsBySpecies = (species) => PET_BREEDS[species] || []
